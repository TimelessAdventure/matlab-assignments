clc; clear all; close all;
M=31; n=0:M-1;
wrect=n>=0;
subplot(251);
stem(n, wrect); title("Rectangular"); ylabel("w(n)"); xlabel("n->"); xlim([-10, 40]);
wrect=rectwin(M);
subplot(256); stem(n, wrect); xlim([-10 40]); title("Rectangular"); ylabel('w(n)'); xlabel('n->');
whann=0.5*(1-cos(2*pi*n/(M-1)));
subplot(252); stem(n, whann); title("Hann"); ylabel("w(n)"); xlabel('n->');
whann=hann(M); 
subplot(257); stem(n, whann); title("Hann"); ylabel("w(n)"); xlabel("n->");
wbart=1-(abs(M-1-2*n)/(M-1));
subplot(253); 
stem(n, wbart); title("Bartlett"); ylabel("w(n)"); xlabel('n->');
wbart=bartlett(M);
subplot(258);
stem(n,wbart); title("Bartlett"); ylabel("w(n)"); xlabel('n->');
wham=0.54-0.46*cos(2*pi*n/(M-1));
subplot(254);
stem(n, wham); title("Hamming"); ylabel("w(n)"); xlabel('n->');
wham=hamming(M);
subplot(259); stem(n, wham); title("Hamming"); ylabel("w(n)"); xlabel("n->");
wblack=(0.42 - 0.5* cos(2*pi*n/(M-1))+ 0.08 * cos(4*pi*n/(M-1)));
subplot(255); 
stem(n, wblack); title("Blackman"); ylabel("w(n)"); xlabel("n->");
wblack=blackman(M);
subplot(2, 5 ,10); stem(n, wblack); title("Blackman"); ylabel("w(n)"); xlabel("n->");